D_VIA = 0.2                         # a row ends with a 0.2 mm 45-degree piece into its via, so the via turn is 45 degrees
STEP = 0.33                         # staircase step: hole radius 0.075 + hole clearance 0.2 + half a track 0.045 = 0.32
