def ladder_end(net):
    x, y = VIA_X[net], VIA_Y[net]
    yc, xc, ch = CHANNEL[net]
    back = [(x, y), (x, round(yc - ch, 4)), (round(x - ch, 4), yc)] + ([(xc, yc)] if xc else []) + ["U2"]
    return {"pieces": [(L4, [(round(x - DV[net], 4), ROW[net]), (x, y)]), ("via", (x, y)), (L1, back)]}


def row_slot(bundle, leg, net, side, n, pitch=0.3, x_leg=X_HARP):
    """Tuning site on an east-west row under the SDRAM: n single-sided humps starting at X_BODY (all blocks begin on
    one vertical line, 0.05 mm inside the package outline). x_leg = x of the leg's first path point."""
    return bundle.slot(net, leg, s0=X_BODY - x_leg, length=2 * pitch * n + 1e-6, side=side, pitch=pitch)


