"""PROTOTYPE (issue 21) variant 3_under_sdram: routes and tuning planned together, tuning under the SDRAM body.

Layer plan (decided before routing, see PLAN.md):
  L4  byte lane 1 and the clock: a "ladder" of nine east-west rows under the SDRAM's west half, one row per net.
      Each row ends at a via in the ball-free centre strip; from there L1 runs south in the strip and west along
      a ball-row channel to the ball. The vias form a staircase (0.33 mm further east per row) so the L1 returns
      nest without crossing. The straight part of every row under the body is that net's reserved tuning site.
      D3 (inner ball, must leave on L4) runs over the top of the ladder and down the SDRAM's east side.
  L6  byte lane 0 and both DQM: NBL1 / NBL0 / D2 on diagonals from the MCU's top right corner (NBL0 = the longest
      net, one straight diagonal, it passes between two staircase vias; D2 ends with 0.8 mm south into its via), D1 / D0 on two diagonals to two rows under
      the SDRAM's west half (their tuning sites), D6 D7 D5 D4 straight east under the SDRAM as in 0_base.
  L1  only ball escapes and the returns under the SDRAM. Nothing on L1 in the corridor, no via in the corridor.
Bundles are generated by lib/bundle.py; what is typed by hand is listed in PLAN.md.
"""
