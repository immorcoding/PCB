"""PROTOTYPE (throwaway, issue 21): build one variant end to end.

    D:\\KiCad\\bin\\python.exe build.py <key>            full build -> out/<key>/  (10-25 s)
    D:\\KiCad\\bin\\python.exe build.py <key> --fast     board + serpentines + lengths and gaps by geometry only (seconds)
    D:\\KiCad\\bin\\python.exe build.py --summary        out/summary.md: one table over every variant that has a metrics.json
    options:  --force     draw explicit serpentines even when they break a limit (to look at them; never a result)
              --no-render  full build without the pictures

A build only writes inside out/<key>/ (and short-lived temp folders under out/_tmp/), so several
variants can be built at the same time. See lib/README.md for the routes.py format.
"""
import json, os, sys, time

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "lib"))
import pcbnew                                               # noqa: E402
import board, serp, lengths, checks                         # noqa: E402
from common import NAME, NETS, REF, WINDOW, LEN_MAX, short, check_lock   # noqa: E402

WINDOW_RULE = """
# --- generated by build.py: every /FMC_* net within +-%.1f mm of %s, L = %.4f mm ---
# It comes after sdram_len_max and replaces it for these nets (a later length rule wins); max is far below 60 mm.
(rule "sdram_window"
  (condition "A.NetName == '/FMC_*'")
  (constraint length (min %.4fmm) (opt %.4fmm) (max %.4fmm)))
"""


def summary():
    """out/summary.md: the same numbers for every built variant, side by side (all read from metrics.json)."""
    rows = []
    for key in sorted(os.listdir(os.path.join(ROOT, "out"))):
        f = os.path.join(ROOT, "out", key, "metrics.json")
        if os.path.isfile(f):
            rows.append(json.load(open(f, encoding="utf-8")))
    o = ["# 各方案的指标（由 `build.py --summary` 从各方案的 metrics.json 生成，不是手抄的）", "",
         "| 方案 | 窗口内 | 离 SDCLK 最远 | SDCLK 长度 | 最长 / 最短 | 绕远合计 | 蛇形合计 | 蛇形处数 / 弯数 | SDRAM 下的蛇形占比 | 凸包面积 | 外包矩形 | 扫过的面积（三层合并） | 窄条里上下占 | 过孔最多 / 合计 | DRC 未连接 / 超窗 / 其他 | 规则生效 | 构建秒数 |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        t, sp, ck = r["totals"], r["space"], r["checks"]
        d = ck["drc"]
        o.append("| `%s` | %d / %d | %s %+.3f | %.3f | %.3f / %.3f | %.2f | %.2f | %d / %d | %.0f%% | %.1f | %.2f × %.2f | %.1f | %.2f | %d / %d | %d / %d / %d | %s | %s |" % (
            r["variant"], t["in_window_count"], t["nets"], short(t["worst_net"]), t["worst_delta_mm"], t["window_L_mm"], t["longest_mm"], t["shortest_mm"],
            t["total_detour_mm"], t["total_serpentine_mm"], t["n_serpentines"], t["n_humps"], 100 * t["serpentine_under_sdram_share"],
            sp["bus_hull_area_mm2"], sp["bus_bbox_mm"][0], sp["bus_bbox_mm"][1], sp["bus_swept_area_mm2"]["all"], sp["channel_width_mm"],
            t["max_vias"], t["total_vias"], d["unconnected"], d["by_type"].get("length_out_of_range", 0), len(d["unexplained"]),
            "OK" if ck["rule_file_canary"]["ok"] and ck["rules_matched"]["ok"] else "失败", r.get("build_seconds", "—")))
    o += ["", "单位 mm、mm²。各项的定义见 README.md；每个方案的逐根数字在 `out/<方案>/tune.txt`。", ""]
    for r in rows:
        o.append("- `%s`：%s" % (r["variant"], r["description"]))
    open(os.path.join(ROOT, "out", "summary.md"), "w", encoding="utf-8").write("\n".join(o) + "\n")
    print("\n".join(o))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = {a for a in sys.argv[1:] if a.startswith("--")}
    if "--summary" in flags:
        sys.stdout.reconfigure(encoding="utf-8")
        return summary()
    if len(args) != 1:
        raise SystemExit(__doc__)
    key = args[0].strip("/\\")
    fast, force = "--fast" in flags, "--force" in flags
    sys.stdout.reconfigure(encoding="utf-8")
    t0 = time.time()
    out = os.path.join(ROOT, "out", key)
    check_lock(out)
    var = board.load_variant(key)
    info = board.build(var, out)
    pcb = os.path.join(out, NAME + ".kicad_pcb")
    B = pcbnew.LoadBoard(pcb)
    print("== %s: %s" % (key, var.DESCRIPTION))
    for n in info["breakout_notes"]:
        print("  convention: " + n)
    try:
        tune = serp.run_tuning(B, var, log=print, force=force)
    except SystemExit:                                      # a serpentine that does not fit: still say what is wrong with the routes
        geo = checks.geometry(pcbnew.LoadBoard(pcb))        # the board as routed, before any serpentine
        for v in geo["clearance_violations"]:
            print("  CLEARANCE (routes, before tuning) %s: %s - %s gap %.3f (needs %.3f) at (%.2f, %.2f)" % (v["layer"], v["net"], v["other"], v["gap"], v["need"], v["at"][0], v["at"][1]))
        for p in geo["path_problems"]:
            print("  PATH (routes, before tuning) " + p)
        raise
    pcbnew.SaveBoard(pcb, B)
    L = tune["predicted"][REF]
    dru = os.path.join(out, NAME + ".kicad_dru")
    open(dru, "a", encoding="utf-8").write(WINDOW_RULE % (WINDOW, REF, L, L - WINDOW, L, L + WINDOW))
    tune["window_L"] = L
    json.dump(tune, open(os.path.join(out, "tune.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)

    geo = checks.geometry(B)
    json.dump(geo, open(os.path.join(out, "geo.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    g = lengths.geometric(B)
    print("  net     natural   +serp    total   to CLK  window  vias  layers            (lengths by geometry, mm)")
    for n in NETS:
        d = g[n]["length"] - g[REF]["length"]
        print("  %-6s %8.3f %7.3f %8.3f  %+7.3f  %-6s  %d    %s" % (
            short(n), tune["natural"][n], g[n]["length"] - tune["natural"][n], g[n]["length"], d,
            "ok" if abs(d) <= WINDOW + 1e-6 and g[n]["length"] <= LEN_MAX else "OUT", g[n]["vias"],
            " ".join("%s %.2f" % kv for kv in g[n]["layers"].items())))
    n_in = sum(1 for n in NETS if abs(g[n]["length"] - g[REF]["length"]) <= WINDOW + 1e-6)
    print("  in window: %d / %d;  window = %.3f .. %.3f" % (n_in, len(NETS), L - WINDOW, L + WINDOW))
    for n, m in tune["missing"].items():
        print("  not fixed by the automatic filler: %s still short by %.3f" % (short(n), m))
    for v in geo["clearance_violations"]:
        print("  CLEARANCE %s: %s - %s gap %.3f (needs %.3f) at (%.2f, %.2f)" % (v["layer"], v["net"], v["other"], v["gap"], v["need"], v["at"][0], v["at"][1]))
    for p in geo["path_problems"]:
        print("  PATH " + p)
    if geo["min_gap_all"]:
        m = geo["min_gap_all"]
        print("  smallest gap between nets: %.3f (%s - %s, %s, at %.2f, %.2f)" % (m["gap"], m["net"], m["other"], m["layer"], m["at"][0], m["at"][1]))
    if fast:
        print("  fast mode: no DRC, no pictures, metrics.json NOT written (%.1f s)" % (time.time() - t0))
        return

    import metrics                                          # noqa: E402
    drc = checks.run_drc(out)
    B = pcbnew.LoadBoard(pcb)                               # the board as kicad-cli saved it (pours filled)
    measured, matched = lengths.probe(out)
    can = checks.canary(out)
    shape = checks.track_shape(out)
    geo = checks.geometry(B)
    json.dump(geo, open(os.path.join(out, "geo.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    res = metrics.collect(key, var, info, tune, B, measured, matched, drc, can, shape, geo)
    if "--no-render" not in flags:
        import render                                       # noqa: E402
        res["pictures"] = render.render_all(B, out, getattr(var, "VIEWS", None))
    res["build_seconds"] = round(time.time() - t0, 1)
    json.dump(res, open(os.path.join(out, "metrics.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    txt = metrics.table(res)
    open(os.path.join(out, "tune.txt"), "w", encoding="utf-8").write(txt)
    print(txt)


if __name__ == "__main__":
    main()
