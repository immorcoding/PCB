"""Regression benchmark for stm32h743_sdram/bga_plan.py (the grid model bga_grid.py / bga_check.py and the planner's
building blocks).

    D:\\KiCad\\bin\\python.exe scripts\\tests\\bga_plan\\check.py [--no-real]

The model runs on the system Python (numpy, scipy, scikit-image; `python` on PATH): model_check.py. This file
compares its answers with expected.json and, for the real-board case, replays the routes the model found for the
balls it calls drawable through scripts/busroute's geometry check on the board of commit 08ca4e9 (taken from
git into a temp folder, fills removed): a "there is room" verdict must be a route busroute accepts.

  synthetic   6 x 6 ball field, ball C3 walled in by four foreign vias          -> C3 blocked, 35 ok
  units       slot staircases (limits 3.0 and 3.5), RTE-2 capacity, order rows
  real        commit 08ca4e9 (stop 7 of issue #22): the 22 routed MCU nets, each without its own copper, all
              have a way; the 18 balls reported as without a way out, judged together: verdicts as pinned
              (the report is reproduced for 11 of them; 7 are drawable together, which the replay proves)

Prints one line, `OK ...` or `FAIL ...`; exit code 0 = pass. About 2 minutes (5 s with --no-real).
"""
import json, os, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
BOARD_DIR = os.path.join(ROOT, "stm32h743_sdram")
N = "stm32h743_sdram"
COMMIT = "08ca4e9"

REPLAY = '''"""Generated by scripts/tests/bga_plan/check.py."""
import json
BOARD = %(board)r
ORIGIN = (100, 100)
GROUP = "bga_plan_bench"
SKETCH = True
OPEN_ENDS = True
YIELD_NETS = ["GND"]


def routes(job):
    R = json.load(open(%(src)r, encoding="utf-8"))
    return {net: [("via", tuple(p[1])) if p[0] == "via" else (p[0], [q if isinstance(q, str) else tuple(q) for q in p[1]]) for p in pcs] for net, pcs in R.items()}
'''


def main():
    real = "--no-real" not in sys.argv
    py = shutil.which("python") or shutil.which("python3")
    if not py or os.path.normcase(os.path.dirname(py)) == os.path.normcase(os.path.dirname(sys.executable)):
        print("FAIL no system Python with numpy / scipy / scikit-image on PATH (the model does not run on KiCad's Python)")
        return 1
    tmp = tempfile.mkdtemp(prefix="bga_plan_bench_")
    try:
        out = os.path.join(tmp, "model.json")
        r = subprocess.run([py, os.path.join(HERE, "model_check.py"), out] + ([] if real else ["--no-real"]), capture_output=True)
        if r.returncode or not os.path.isfile(out):
            print("FAIL model_check.py: exit %d\n%s" % (r.returncode, (r.stdout + r.stderr).decode("utf-8", "replace")[-2000:]))
            return 1
        got = json.load(open(out, encoding="utf-8"))
        exp = json.load(open(os.path.join(HERE, "expected.json"), encoding="utf-8"))
        bad = []
        if got["synthetic"] != exp["synthetic"]:
            bad.append("synthetic: " + ", ".join("%s %s (expected %s)" % (k, v, exp["synthetic"].get(k)) for k, v in sorted(got["synthetic"].items()) if exp["synthetic"].get(k) != v))
        for k, v in exp["units"].items():
            if json.loads(json.dumps(got["units"].get(k))) != v:
                bad.append("units %s: %s (expected %s)" % (k, got["units"].get(k), v))
        note = "synthetic %d balls (%s blocked), units %d" % (len(got["synthetic"]), ",".join(k for k, v in sorted(got["synthetic"].items()) if v == "blocked"), len(exp["units"]))
        if real:
            g, e = got["real"], exp["real"]
            for n, v in sorted(g["routed"].items()):
                if v[0] not in ("ok", "detour") or v != e["routed"].get(n):
                    bad.append("routed %s: %s (expected %s)" % (n, v, e["routed"].get(n)))
            for b, v in sorted(g["known"].items()):
                if v[0] != e["known"].get(b, [None])[0]:
                    bad.append("known %s: %s (expected %s)" % (b, v[0], e["known"].get(b, [None])[0]))
            # replay the routes of the balls called drawable on the board of that commit
            bd = os.path.join(tmp, "board")
            os.makedirs(bd)
            for ext in (".kicad_pcb", ".kicad_pro", ".kicad_dru"):
                data = subprocess.run(["git", "-C", ROOT, "show", "%s:%s/%s%s" % (COMMIT, N, N, ext)], capture_output=True).stdout
                open(os.path.join(bd, N + ext), "wb").write(data)
            subprocess.run([sys.executable, os.path.join(BOARD_DIR, "copper_report.py"), "unfill", os.path.join(bd, N + ".kicad_pcb")], capture_output=True)
            src = os.path.join(tmp, "pieces.json")
            json.dump(g["pieces"], open(src, "w", encoding="utf-8"))
            rf = os.path.join(tmp, "routes_replay.py")
            open(rf, "w", encoding="utf-8", newline="\n").write(REPLAY % dict(board="board/%s.kicad_pcb" % N, src=src.replace("\\", "/")))
            rr = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "busroute", "build.py"), rf, "--fast"], capture_output=True)
            text = (rr.stdout + rr.stderr).decode("utf-8", "replace")
            hard = [l for l in text.splitlines() if l.startswith("  ! ")]
            if hard or "GAP 0" not in text:
                bad.append("replay of %d routes: %d findings stop the build: %s" % (len(g["pieces"]), len(hard), "; ".join(h.strip() for h in hard[:4]) or text[-300:]))
            c = {}
            for b, v in g["known"].items():
                c[v[0]] = c.get(v[0], 0) + 1
            note += "; real: 22 routed all with a way, the 18 reported balls judged together %s, %d routes replayed through busroute with 0 findings (%.0f s)" % (
                ", ".join("%s %d" % kv for kv in sorted(c.items())), len(g["pieces"]), sum(g["seconds"]))
        if bad:
            print("FAIL bga_plan: " + " | ".join(bad))
            return 1
        print("OK bga_plan: " + note)
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
