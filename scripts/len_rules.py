"""Generate the length-window rules of a board from its routed reference nets (RTE-2).

    D:\\KiCad\\bin\\python.exe scripts\\len_rules.py <board>.kicad_pcb            rewrite the generated block
    D:\\KiCad\\bin\\python.exe scripts\\len_rules.py <board>.kicad_pcb --check    report only, exit 1 if stale or a sum fails

"Every data line within +-2.5 mm of the clock" cannot be written as a KiCad `skew` rule (its reference
is the longest net of the group, not a net you name), so each group gets a `length (min) (opt) (max)`
window whose numbers are computed here from the reference net as KiCad's DRC measures it (pad centre to
pad centre, plus the height of the layers each via crosses). The reference moves when it is rerouted,
so this runs on every build; --check tells whether the block in the rule file is still current.

Input: length_groups.json next to the board:
  groups: [{rule, members (a rule condition), ref: [nets, summed: a series resistor splits a net],
            lo, hi (mm relative to the reference; either may be omitted), cap (absolute max, optional)}]
  sums:   [{name, nets: [summed], plus_longest_of: [nets] (optional), max}]   checked here, not by DRC
  fixed:  [{rule, members, constraint (KiCad text, e.g. "skew (max 45mm)"), why (optional)}]   written as given;
          for limits that need no reference but must win over a static rule of the hand-written part (the
          block is last in the file, and the last matching rule of a constraint type wins)
The block is written between the two marker lines of the .kicad_dru; it must be last in the file so
that it wins over the static max-length rules for the nets it covers.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import drc_probe

BEGIN = "# >>> generated by scripts/len_rules.py from length_groups.json -- do not edit between the markers"
END = "# <<< generated"


def unrouted_nets(board_path):
    """Nets that still have an unconnected item (their measured length would be a partial length)."""
    out = set()
    for u in drc_probe.run_drc(board_path).get("unconnected_items", []):
        for it in u["items"]:
            n = drc_probe.net_of(it)
            if n:
                out.add(n)
    return out


def build(board_path):
    """(block text, [report lines], ok)"""
    spec = json.load(open(os.path.join(os.path.dirname(os.path.abspath(board_path)), "length_groups.json"), encoding="utf-8"))
    nets = set()
    for g in spec.get("groups", []):
        nets.update(g["ref"])
    for s in spec.get("sums", []):
        nets.update(s["nets"]); nets.update(s.get("plus_longest_of", []))
    got = drc_probe.measure_lengths(board_path, {n: "A.NetName == '%s'" % n for n in sorted(nets)})
    length = {n: got[n].get(n) for n in nets}
    open_nets = unrouted_nets(board_path)
    usable = lambda n: length[n] is not None and n not in open_nets
    why = lambda ns: ", ".join("%s %s" % (n, "not routed" if length[n] is None else "has unconnected ends") for n in ns if not usable(n))
    lines, report, ok = [BEGIN], [], True
    for g in spec.get("groups", []):
        if not all(usable(n) for n in g["ref"]):
            lines.append("# %s: no rule yet (%s)" % (g["rule"], why(g["ref"])))
            report.append("%s: 没有生成（基准 %s）" % (g["rule"], why(g["ref"])))
            continue
        ref = sum(length[n] for n in g["ref"])
        lo = ref + g["lo"] if "lo" in g else None
        hi = ref + g["hi"] if "hi" in g else None
        if "cap" in g:
            hi = g["cap"] if hi is None else min(hi, g["cap"])
        c = "".join(" (%s %.4fmm)" % kv for kv in (("min", lo), ("opt", ref if lo is not None and hi is not None else None), ("max", hi)) if kv[1] is not None)
        lines += ["# %s: reference %s = %.4f mm" % (g["rule"], " + ".join(g["ref"]), ref),
                  '(rule "%s"\n  (condition "%s")\n  (constraint length%s))' % (g["rule"], g["members"], c)]
        report.append("%s: 基准 %s = %.4f mm，窗口 %s … %s mm" % (
            g["rule"], " + ".join(g["ref"]), ref, "%.4f" % lo if lo is not None else "不限", "%.4f" % hi if hi is not None else "不限"))
    for x in spec.get("fixed", []):
        lines += ["# %s: fixed%s" % (x["rule"], " (%s)" % x["why"] if x.get("why") else ""),
                  '(rule "%s"\n  (condition "%s")\n  (constraint %s))' % (x["rule"], x["members"], x["constraint"])]
        report.append("%s: 固定 %s" % (x["rule"], x["constraint"]))
    for s in spec.get("sums", []):
        need = s["nets"] + s.get("plus_longest_of", [])
        if not all(usable(n) for n in s["nets"]) or (s.get("plus_longest_of") and not any(usable(n) for n in s["plus_longest_of"])):
            report.append("%s: 没法算（%s）" % (s["name"], why(need)))
            continue
        tot = sum(length[n] for n in s["nets"]) + max([length[n] for n in s.get("plus_longest_of", []) if usable(n)], default=0.0)
        good = tot <= s["max"]
        ok = ok and good
        report.append("%s: %.4f mm，上限 %g mm，%s" % (s["name"], tot, s["max"], "通过" if good else "超出 %.4f mm" % (tot - s["max"])))
    lines.append(END)
    return "\n".join(lines) + "\n", report, ok


def main(argv):
    board = argv[0]
    dru = os.path.splitext(board)[0] + ".kicad_dru"
    text = open(dru, encoding="utf-8").read()
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", text, re.S)
    if not m:
        sys.exit("FAIL: marker lines not found in " + dru)
    if text[m.end():].strip():
        sys.exit("FAIL: the generated block must be the last thing in " + dru)
    block, report, ok = build(board)
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(report))
    if "--check" in argv:
        stale = m.group(0).strip() != block.strip()
        print("生成段%s" % ("已过期：重新跑 len_rules.py" if stale else "是最新的"))
        return 1 if stale or not ok else 0
    if m.group(0) != block:
        open(dru, "w", encoding="utf-8", newline="\n").write(text[:m.start()] + block)
        print("已更新 " + os.path.basename(dru))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
